/**
 * 端口 —— core 里**唯一**的可替换实现。
 *
 * ## 为什么只剩一个
 *
 * 用户的判据：「别人可能想换实现的才拆，关不掉的重依赖不拆。」
 *
 * | 东西 | 可替换？ | 现在在哪 |
 * |---|---|---|
 * | **存储** | ✅ 用户明确说「后端存储可能想要不同实现」 | **本文件（端口）** |
 * | ~~搜索~~ | ❌ 用户后来改口：「就强耦合吧」 | `search.ts`（强依赖） |
 * | 模板 / 状态机 / 关系 / 工作空间 | ❌ 用户：「让别人关掉模板是不可能的」 | core 各模块 |
 *
 * ## 搜索为什么不再是端口
 *
 * 用户原话：
 *
 * > 「不。是把搜索并入 core 强依赖。ui 和 tool 都强依赖搜索，替换了搜索，
 * >   那接口也没法做啊。他只能说替换底层实现，那没有意义。要么他增加 api，
 * >   那又调用不了。所以没意义。就强耦合吧。」
 *
 * ⇒ 搜索的**结果形状**被 UI（筛选器 / 列表）和 AI 工具（列表返回）直接消费。
 *   换实现如果形状不同，消费方用不了；形状相同，换它就没意义。
 *   **可替换性在这里是假的**，所以删掉这个假接口。
 *
 * ## 接口必须窄
 *
 * 用户原话：「storage 没有查询的必要。一旦 ui 查看就是全量加载。」
 * ⇒ `CardStore` **没有** `query` / `index` / `transaction`。
 * 换一个实现只要满足四个操作 + `close`，不需要实现一套查询引擎。
 */

import type { Card } from './card.ts';

/**
 * 卡的持久化端口 —— **core 唯一的可替换实现**。
 *
 * ## 五个操作就够
 *
 * · `loadAll` —— 一个工作空间的全部卡（**含草稿、含墓碑**，由调用方过滤）；
 * · `save` —— 写一张卡（新增或整体覆盖）；
 * · `kvGet` / `kvSet` —— 不按空间分的全局键值（工作空间索引、归档标记）；
 * · `close` —— 释放底层资源。
 *
 * ## ⚠ `save` 的原子性由实现保证
 *
 * 契约是「一次写一张卡」。实现必须保证**这张卡的写入是原子的**
 * （SQLite 用单行 UPDATE；JSON 实现用写临时文件再 rename）。
 * 若实现退化成「重写整个列表」，1000 张卡每次编辑要写 2MB ——
 * 那是另一种载体，不是本接口的错。
 *
 * ## ⚠ `loadAll` 不过滤
 *
 * 返回值包含 `deleted: true` 的墓碑。过滤是调用方的事 —— 因为
 * 「按 id 直查要能看到墓碑」和「列表不列墓碑」是两条不同的读路径。
 */
export interface CardStore {
	/** 一个工作空间的全部卡（含墓碑）。 */
	loadAll(workspaceId: string): readonly Card[];
	/** 写一张卡（新增或整体覆盖）。 */
	save(workspaceId: string, card: Card): Promise<void>;
	/** 读全局键值；不存在返回 `undefined`。 */
	kvGet(key: string): string | undefined;
	/** 写全局键值；`undefined` = 删除该键。 */
	kvSet(key: string, value: string | undefined): Promise<void>;
	/** 关闭底层资源（进程退出 / 测试清理用）。 */
	close(): Promise<void>;
}

